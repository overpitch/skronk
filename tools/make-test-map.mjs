// Generates public/assets/maps/test_box.map: a box room with stairs, a ramp, a
// pillar, a jumpable wall and one portal-friendly wall. It exists to test the
// loader and movement; Dave's own maps get drawn in TrenchBroom.
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const SURF_PORTAL = 1;

const cross = (a, b) => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
const addv = (a, b) => [a[0] + b[0], a[1] + b[1], a[2] + b[2]];

/** Integer vector perpendicular to integer normal n. */
function perp(n) {
  const abs = n.map(Math.abs);
  const i = abs.indexOf(Math.min(...abs));
  const e = [0, 0, 0];
  e[i] = 1;
  return cross(n, e);
}

function texAxes(n) {
  const [ax, ay, az] = n.map(Math.abs);
  if (az >= ax && az >= ay) return [[1, 0, 0], [0, -1, 0]];
  if (ax >= ay) return [[0, 1, 0], [0, 0, -1]];
  return [[1, 0, 0], [0, 0, -1]];
}

/** One face line. Outward integer normal n, integer point p on the plane. */
function face(n, p, tex, flags = 0) {
  const a = perp(n);
  const b = cross(n, a);
  // cross(p0 - p1, p2 - p1) = cross(a, b) = n * |a|^2, so the normal points out.
  const pts = [addv(p, a), p, addv(p, b)];
  const [u, v] = texAxes(n);
  const fmt = (q) => `( ${q.join(" ")} )`;
  return `${pts.map(fmt).join(" ")} ${tex} [ ${u.join(" ")} 0 ] [ ${v.join(" ")} 0 ] 0 1 1 0 ${flags} 0`;
}

/** Axis-aligned box. `tex` is a string or a function (normal) => [texture, flags]. */
function box(mins, maxs, tex) {
  const t = typeof tex === "function" ? tex : () => [tex, 0];
  const sides = [
    [[-1, 0, 0], mins],
    [[1, 0, 0], maxs],
    [[0, -1, 0], mins],
    [[0, 1, 0], maxs],
    [[0, 0, -1], mins],
    [[0, 0, 1], maxs],
  ];
  return sides.map(([n, p]) => face(n, p, ...t(n)));
}

const brushes = [];
const B = (faces) => brushes.push(faces);

// Room shell: interior x,y in [-512, 512], z in [0, 384].
B(box([-528, -528, -16], [528, 528, 0], "base/floor"));
B(box([-528, -528, 384], [528, 528, 400], "base/ceiling"));
B(box([-528, -528, 0], [-512, 528, 384], "base/wall"));
// East wall: the face pointing into the room is portal-friendly.
B(box([512, -528, 0], [528, 528, 384], (n) => (n[0] === -1 ? ["base/portal_panel", SURF_PORTAL] : ["base/wall", 0])));
B(box([-512, -528, 0], [512, -512, 384], "base/wall"));
B(box([-512, 512, 0], [512, 528, 384], "base/wall"));

// Pillar.
B(box([-264, 136, 0], [-136, 264, 384], "base/trim"));

// Platform against the east wall, with three 16-unit steps leading up to it.
B(box([192, -512, 0], [512, -256, 64], "base/trim"));
for (let k = 1; k <= 3; k++) {
  B(box([256, -256 + (3 - k) * 32, 0], [384, -256 + (4 - k) * 32, 16 * k], "base/trim"));
}

// Ledge in the north-west corner, reached by a ramp rising 128 over 256 units.
B(box([-512, 256, 0], [-320, 512, 128], "base/trim"));
B([
  face([0, 0, -1], [0, 0, 0], "base/trim"),
  face([-1, 0, 0], [-512, 0, 0], "base/trim"),
  face([1, 0, 0], [-384, 0, 0], "base/trim"),
  face([0, 1, 0], [0, 256, 0], "base/trim"),
  face([0, -1, 2], [0, 0, 0], "base/floor"), // slope: z = y / 2
]);

// A wall too tall to step over (40) but low enough to jump (max jump ~45).
B(box([-128, 300, 0], [128, 316, 40], "base/trim"));

const pointEntity = (props) =>
  `{\n${Object.entries(props).map(([k, v]) => `"${k}" "${v}"`).join("\n")}\n}`;

const out = [
  "// Game: Skronk",
  "// Format: Quake2 (Valve)",
  "// Generated by tools/make-test-map.mjs. Edit that script, not this file.",
  "// entity 0",
  "{",
  '"classname" "worldspawn"',
  '"mapversion" "220"',
  ...brushes.flatMap((faces, i) => [`// brush ${i}`, "{", ...faces, "}"]),
  "}",
  pointEntity({ classname: "player_spawn", origin: "0 -300 25", angle: "90" }),
  pointEntity({ classname: "player_spawn", origin: "-300 0 25", angle: "0" }),
  pointEntity({ classname: "player_spawn", origin: "300 300 25", angle: "180" }),
  pointEntity({ classname: "player_spawn", origin: "100 100 25", angle: "270" }),
  pointEntity({ classname: "pickup_health", origin: "352 -384 81", amount: "25" }),
  pointEntity({ classname: "pickup_armor", origin: "-416 384 145", amount: "50" }),
  pointEntity({ classname: "pickup_ammo", origin: "0 400 17", amount: "20" }),
  pointEntity({ classname: "light", origin: "0 0 320", light: "400" }),
  pointEntity({ classname: "light", origin: "352 -384 300", light: "250", _color: "1 0.85 0.6" }),
  pointEntity({ classname: "light", origin: "-416 384 300", light: "250", _color: "0.6 0.8 1" }),
].join("\n");

const dest = resolve(import.meta.dirname, "../public/assets/maps/test_box.map");
writeFileSync(dest, out + "\n");
console.log(`wrote ${dest} (${brushes.length} brushes)`);
